TEAM_ABBR = {"楽": "라쿠텐", "ソ": "소프트뱅크", "神": "한신", "巨": "요미우리", "ヤ": "야쿠르트", "中": "주니치",
             "広": "히로시마", "デ": "DeNA", "日": "니혼햄", "ロ": "롯데", "西": "세이부", "オ": "오릭스"}
OUT_TOKEN = re.compile(r"^(?:(\d)アウト)?(" + BASE_RE + r")?$")


def split_tail(t):
    """문장 끝의 점수('ソ 0-2 ロ')·아웃·주자('1アウト二塁') 표기를 떼어 낸다 → (본문, 점수, 아웃 수, 주자)"""
    toks = [x for x in t.split(" ") if x]   # 전각 공백(교체 문장 구분)은 그대로 둔다
    score, outs, base = None, None, ""
    if len(toks) >= 2:
        m = OUT_TOKEN.match(toks[-1])
        if m and toks[-1]:
            outs = int(m.group(1)) if m.group(1) else None
            base = BASE_JP.get(m.group(2) or "", "")
            toks = toks[:-1]
    if len(toks) >= 4 and toks[-3] in TEAM_ABBR and toks[-1] in TEAM_ABBR and re.match(r"^\d+-\d+$", toks[-2]):
        a, b = toks[-2].split("-")
        score = {"away": TEAM_ABBR[toks[-3]], "a": int(a), "b": int(b), "home": TEAM_ABBR[toks[-1]]}
        toks = toks[:-3]
    return " ".join(toks), score, outs, base


def tidy(t):
    t = t.replace("　", " ").replace("！", "!").replace("、", ", ").replace("。", ". ").replace("：", ":")
    t = re.sub(r"\s*→\s*", " → ", t)
    t = re.sub(r"\s{2,}", " ", t)
    t = re.sub(r"\s+([!,.)])", r"\1", t)
    t = re.sub(r"\(\s+", "(", t)
    t = re.sub(r"\s+(\{(?:을|이|은|와|으로)\})", r"\1", t)
    t = re.sub(r"([가-힣A-Za-z])(\d+점)", r"\1 \2", t)
    t = resolve_josa(t)
    return t.strip(" ,")


def ko_line(text, team_replace=None, name_fn=None):
    """문자중계 한 줄 → (한국어 문장, 점수, 아웃 수, 주자). 링크된 선수 이름은 미리 한국어로 바꿔서 넣는다.
    name_fn: 링크 없이 글에만 나오는 이름('ロッテ・寺地の…')을 바꾸는 함수."""
    t = (text or "").strip()
    if name_fn:
        t = re.sub(r"・([^・の\s、]+?)の", lambda m: "・" + name_fn(m.group(1)) + "の", t)
    if team_replace:
        t = team_replace(t)
    body, score, outs, base = split_tail(t)
    s = body
    for pat, rep in PRE_RULES:
        s = re.sub(pat, rep, s)
    s = _pitch_phrase(s)
    for pat, rep in RULES:
        s = re.sub(pat, rep, s)
    s = s.replace("から", "에서 ").replace("で", " ").replace("の", " ").replace("を", " ").replace("が", " ")
    return tidy(s), score, outs, base


