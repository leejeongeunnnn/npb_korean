# ----------------------------------------------------------------------------
# 조사: '{을}' '{이}' '{은}' '{으로}' '{와}' 표시를 앞 글자 받침에 맞춰 고른다
# ----------------------------------------------------------------------------
_JOSA = {"을": ("을", "를"), "이": ("이", "가"), "은": ("은", "는"), "와": ("과", "와"), "으로": ("으로", "로")}
_DIGIT_BATCHIM = {"0": True, "1": True, "2": False, "3": True, "4": False, "5": False,
                  "6": True, "7": True, "8": True, "9": False}


def _has_batchim(ch, rieul_ok=False):
    """받침 여부. rieul_ok=True 면 ㄹ 받침은 받침 없는 것으로 본다('으로/로' 규칙)."""
    if ch in _DIGIT_BATCHIM:
        if rieul_ok and ch in "178":      # 일·칠·팔 = ㄹ 받침
            return False
        return _DIGIT_BATCHIM[ch]
    code = ord(ch) - 0xAC00
    if not (0 <= code < 11172):
        return False
    jong = code % 28
    if rieul_ok and jong == 8:
        return False
    return jong != 0


def resolve_josa(t):
    def rep(m):
        before, kind = m.group(1), m.group(2)
        base = re.sub(r"[)\]）」\s!]+$", "", before)   # '(포수)를' → 괄호 앞 글자로 판단
        last = base[-1] if base else ""
        yes, no = _JOSA[kind]
        return before + (yes if _has_batchim(last, rieul_ok=(kind == "으로")) else no)
    prev = None
    while prev != t:
        prev = t
        t = re.sub(r"(.{0,6}?)\{(을|이|은|와|으로)\}", lambda m: rep(m), t, count=1)
    return t


