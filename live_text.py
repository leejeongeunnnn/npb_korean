def _loc(m_side, m_height):
    side = {"ど真ん中": "한가운데", "真ん中": "가운데", "内角": "몸쪽", "外角": "바깥쪽"}.get(m_side or "", "")
    height = {"高め": "높은", "低め": "낮은"}.get(m_height or "", "")
    return " ".join(x for x in (side, height) if x)


def _pitch_phrase(t):
    """'内角低めの真っ直ぐ' → '몸쪽 낮은 직구', '11球目の真っ直ぐ' → '11구째 직구'."""
    def rep(m):
        loc = _loc(m.group(1), m.group(2))
        p = PITCH_KO[m.group(3)]
        if not loc and m.group(0).startswith("の"):
            return f"의 {p}"     # '〈투수〉のカーブ' → '투수의 커브'
        return f"{loc} {p}".strip()
    t = re.sub(r"(?<![四死打送落制悪投])(ど真ん中|真ん中|内角|外角)?(高め|低め)?(?:いっぱい)?の?(" + PITCH_RE + ")(?=を|に|で|は|、|$)",
               lambda m: rep(m) if (m.group(1) or m.group(2) or m.group(0).endswith(m.group(3))) else m.group(0), t)
    t = re.sub(r"(\d+)球目に", r"\1구째에 ", t)
    t = re.sub(r"(\d+)球目(?:の)?", r"\1구째 ", t)
    return t


